/** 按工作流为种子认领补全「认领→提交→审核→终态」完整流转日志 */
function enrichSeedTaskInstances(
  instances: Array<Omit<TaskInstance, 'logs'> & { logs?: TaskInstanceLog[] }>,
): TaskInstance[] {
  return instances.map((raw) => {
    const task = seedTasks.find((t) => t.id === raw.taskId)
    const workflow = seedTaskWorkflows.find((w) => w.id === task?.workflowId)
    if (!workflow) {
      return { ...raw, logs: raw.logs ?? [] }
    }

    const instance: TaskInstance = {
      ...raw,
      logs: undefined,
    }
    let logs = synthesizeDetailedInstanceLogs(instance, workflow)

    // 演示样例：保留人工干预 / 操作日志附加信息
    if (raw.id === 'ti_003') {
      logs = [
        {
          id: 'log_ti003_reassign',
          title: '操作日志：人工干预-转派',
          tag: '人工干预',
          operator: '运营-李芳',
          time: '2026-07-09T14:20:00.000Z',
          description: '因原灵工王建国未及时响应，将任务转派至刘洋。',
          kind: 'manual',
        },
        ...logs,
        {
          id: 'log_ti003_op',
          title: '上传客户签名凭证',
          tag: '操作日志',
          operator: '刘洋',
          time: '2026-07-10T11:30:00.000Z',
          description: '已上传客户签名及现场照片，等待提交审核。',
          kind: 'operation',
        },
      ]
    }

    if (raw.id === 'ti_009') {
      logs = logs.map((l) =>
        l.title.includes('已取消')
          ? {
              ...l,
              title: '人工干预：强制取消任务',
              tag: '人工干预',
              operator: '管理员',
              description: '灵工主动放弃，运营强制取消认领。',
              kind: 'manual' as const,
            }
          : l,
      )
    }

    return { ...instance, logs }
  })
}

