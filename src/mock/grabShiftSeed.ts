import { DEFAULT_WORKFORCE_ENTERPRISE_ID } from '@/constants/department'
import { seedEnterprisePositions } from '@/mock/positionSeed'
import type { GrabShiftSlot } from '@/types'

function withPositionSnapshot(slot: GrabShiftSlot): GrabShiftSlot {
  if (slot.positionProfile) return slot
  const pos = seedEnterprisePositions.find(
    (p) =>
      p.enterpriseId === DEFAULT_WORKFORCE_ENTERPRISE_ID &&
      (p.profile.positionName === slot.positionName || p.name === slot.positionName),
  )
  if (!pos) return slot
  return {
    ...slot,
    positionId: slot.positionId ?? pos.id,
    positionProfile: {
      ...pos.profile,
      skills: slot.requirements?.length ? slot.requirements : pos.profile.skills,
      requirements: slot.positionRequirement || pos.profile.requirements,
    },
  }
}

