function hourlyItem(
  id: string,
  title: string,
  date: string,
  hours: number,
  rate: number,
): WorkerIncomeDetailItem {
  return {
    id,
    title,
    date,
    unitPrice: rate,
    quantity: hours,
    calcType: 'hourly',
    amount: hours * rate,
  }
}

function taskItem(
  id: string,
  title: string,
  date: string,
  count: number,
  unitPrice: number,
): WorkerIncomeDetailItem {
  return {
    id,
    title,
    date,
    unitPrice,
    quantity: count,
    calcType: 'task',
    amount: count * unitPrice,
  }
}

/** 每个任务一行（任务数量固定为 1） */
function singleTaskItem(
  id: string,
  title: string,
  date: string,
  unitPrice: number,
): WorkerIncomeDetailItem {
  return taskItem(id, title, date, 1, unitPrice)
}

function sumItems(items: WorkerIncomeDetailItem[]) {
  return items.reduce((s, i) => s + i.amount, 0)
}

