import {
  messageCategoryToLegacyType,
  type WorkbenchMessageCategory,
} from '@/constants/workbenchMessage'
import type { Notification } from '@/types'

function msg(
  id: string,
  category: WorkbenchMessageCategory,
  title: string,
  content: string,
  createdAt: string,
  read: boolean,
): Notification {
  return {
    id,
    category,
    portal: 'platform',
    type: messageCategoryToLegacyType(category),
    title,
    content,
    createdAt,
    read,
  }
}

